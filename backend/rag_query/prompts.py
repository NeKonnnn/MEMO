"""
Единые инструкции для ответов по контексту документов (ru/en).

Политика по умолчанию — мягкий RAG:
  - если в CONTEXT есть хоть какие-то зацепки, модель ОБЯЗАНА дать ответ,
    собирая максимум из найденных фрагментов и честно помечая, чего в тексте нет;
  - каноническая фраза «не нашёл» выводится ТОЛЬКО когда CONTEXT буквально пуст
    (этот случай обрабатывается на стороне backend: до вызова LLM).

Жёсткий режим (старое поведение) можно вернуть переменной окружения
RAG_STRICT_ANSWER_MODE=strict — модель будет отвечать канонической фразой, как только
нет прямой опоры, даже если есть косвенные зацепки.

Правила оформления ответа задаются отдельно от правил работы с контекстом, потому что
они обязательные: их нельзя отменить пользовательским промптом (см.
```merge_strict_rag_system_prompt```).

  - RAG_CITE_SOURCES=1   — вернуть старые ссылки вида ```[имя_файла, чанк N]```
                          (по умолчанию выключено: пользователь служебной разметки
                          не видит, и ссылка на «фрагмент 3» для него бессмысленна);
  - RAG_ANSWER_SUMMARY=0 — отключить требование итога в конце ответа;
  - RAG_ANSWER_GAPS_NOTE=0 — отключить абзац «Примечание:» о том, чего в загруженных
                          документах нет (по умолчанию включён)
"""

from __future__ import annotations

import os
from typing import Optional

RAG_STRICT_NOT_FOUND_MESSAGE = (
    "Извините, не нашёл ничего в базе документов по вашему запросу. "
    "Попробуйте переформулировать вопрос или проверьте, что нужные файлы загружены."
)

RAG_NO_EVIDENCE_DETAIL = "Ответ без опоры на загруженные файлы я не формирую, чтобы не выдумывать факты."

def _env_flag(name: str, default: bool) -> bool:
    raw = (os.environ.get(name) or "").strip().lower()
    if not raw:
        return default
    if raw in ("0", "false", "no", "off"):
        return False
    if raw in ("1", "true", "yes", "on"):
        return True
    return default

def _strict_answer_mode() -> str:
    """soft (по умолчанию) | strict.

    soft  — LLM всегда пытается ответить, если в CONTEXT есть хоть какой-то материал,
            и честно указывает, чего не хватает.
    strict — LLM выводит каноническую фразу «не нашёл», если прямой опоры нет.
    """
    v = (os.environ.get("RAG_STRICT_ANSWER_MODE") or "soft").strip().lower()
    return "strict" if v in ("strict", "1", "true", "yes", "on", "hard") else "soft"

def cite_sources_enabled() -> bool:
    """По умолчанию False: ссылки на чанки в ответ пользователя не выводятся."""
    return _env_flag("RAG_CITE_SOURCES", False)

def answer_summary_enabled() -> bool:
    """По умолчанию True: ответ завершается кратким итогом."""
    return _env_flag("RAG_ANSWER_SUMMARY", True)

def answer_gaps_note_enabled() -> bool:
    """По умолчанию True: абзац «Примечание:» о том, чего нет в документах."""
    return _env_flag("RAG_ANSWER_GAPS_NOTE", True)

# --- Правила работы с контекстом -------------------------------------------
# Только про то, ЧТО отвечать. Оформление — ниже, отдельными блоками.

SOFT_CONTEXT_RULES = (
    "Правила ответа по CONTEXT (мягкий RAG):\n"
    "- Главный приоритет — помочь пользователю. Если в CONTEXT есть ХОТЬ КАКИЕ-ТО "
    "зацепки по сути вопроса (определения, смежные факты, упоминания), дай содержательный "
    "ответ на основе этих фрагментов. Не отказывайся, пока в CONTEXT вообще есть текст.\n"
    "- Объединяй факты из нескольких фрагментов в связный ответ. Допускаются разумные "
    "обобщения и перефраз, но без выдумывания конкретики (имён, дат, чисел), которых нет в CONTEXT.\n"
     "- Если ответ получается частичным — дай, что есть, а чего не хватает, вынеси "
    "в отдельный абзац «Примечание:» в конце (см. правила оформления).\n"
    "- Если CONTEXT ПУСТОЙ или полностью НЕ РЕЛЕВАНТЕН теме (там действительно нет ни "
    "прямых, ни косвенных зацепок), тогда — и только тогда — скажи ТОЛЬКО следующий текст:\n"
    f"{RAG_STRICT_NOT_FOUND_MESSAGE}"
)

STRICT_CONTEXT_RULES_LEGACY = (
    "Правила ответа (строгий RAG):\n"
    "- Используй только предоставленный контекст (CONTEXT). Не опирайся на общие знания, если факта нет в CONTEXT.\n"
    "- Если в CONTEXT есть **частичный** ответ — дай его чётко; явно укажи, чего в тексте нет. "
    "Объединяй факты из **нескольких** фрагментов в связный ответ, если они относятся к вопросу.\n"
    f"- Если в CONTEXT **совсем нет** материала по сути вопроса (ни прямых, ни косвенных зацепок), скажи ТОЛЬКО следующий текст целиком:\n"
    f"{RAG_STRICT_NOT_FOUND_MESSAGE}\n"
    "- Не выдумывай детали (имена, цифры, даты), которых нет в CONTEXT."
)

STRICT_CONTEXT_RULES = SOFT_CONTEXT_RULES

# --- Правила оформления ответа ---------------------------------------------
# Обязательные: применяются и к пользовательскому промпту тоже.

# Запрет служебной разметки. Формулировка намеренно перечисляет конкретные утечки:
# сам CONTEXT приходит размеченным («Фрагмент 3 (документ «X.docx», чанк 7,
# релевантность: 84%)»), и без явного запрета модель эту разметку копирует в ответ.
NO_SERVICE_MARKUP_RULE = (
    "Оформление ответа:\n"
    "- Пиши так, как будто знаешь материал сам. В ответе НЕ должно быть служебной "
    "разметки контекста: слов «CONTEXT», «фрагмент», «чанк», номеров фрагментов и чанков, "
    "процентов релевантности, ссылок вида [имя_файла, чанк N]. Пользователь этой разметки "
    "не видит — для него «фрагмент 3» ничего не значит.\n"
    "- Название документа упоминай в тексте только тогда, когда это само по себе полезно "
    "(«в регламенте от 2024 года указано…») или когда пользователь спросил про источник. "
    "Не подписывай источником каждое предложение.\n"
    "- Оборот «в загруженных документах» разрешён и нужен в примечании о неполноте "
    "(см. ниже) — это не служебная разметка, а честное указание границ ответа."
)

# Абзац «Примечание:» о том, чего в документах нет.
# Было до правки промпта 30.07 и пропало вместе со старым строгим блоком — при том,
# что для ВНД это самая полезная часть ответа: она показывает границы регламента,
# а не границы поиска.
GAPS_NOTE_RULE = (
    "Примечание о неполноте:\n"
    "- Если по какой-то части вопроса в CONTEXT данных нет — заверши ответ отдельным "
    "абзацем, начинающимся со слова «Примечание:», и перечисли, чего именно нет "
    "в загруженных документах.\n"
    "- Формулируй в терминах предметной области, а не поиска: «в загруженных документах "
    "не содержится информации о сроках предоставления отчётности», а НЕ «в найденных "
    "фрагментах/чанках нет».\n"
    "- Если уместно, добавь одной фразой, к чему относится сказанное выше "
    "(«указанные положения отражают общий регламентный порядок»).\n"
    "- Примечание идёт ПЕРЕД итогом.\n"
    "- Если вопрос закрыт полностью — примечание не пиши. Не выдумывай недостающее "
    "ради формы и не перечисляй всё, чего в документах нет вообще: только то, что "
    "относится к заданному вопросу."
)

# Старое поведение — если ссылки на чанки кому-то нужны (RAG_CITE_SOURCES=1).
CITATION_RULE = (
    "Оформление ответа:\n"
    "- По возможности помечай источник фактов: [имя_файла, чанк N]. "
    "Если источник неочевиден — формулируй осторожно."
)

SUMMARY_RULE = (
    "Итог в конце ответа:\n"
    "- Заверши ответ короткой выжимкой того, что уже сказано выше.\n"
    "- Если в вопросе было несколько пунктов или ты разобрал несколько тем — вынеси итог "
    "отдельным абзацем «Итого:» и пройди по каждому пункту одной фразой "
    "(«по первому — …, по второму — …»).\n"
    "- Если вопрос был один — хватит одного-двух предложений, начиная со слов вроде "
    "«Итого» или «Если коротко».\n"
    "- Если весь ответ и так укладывается в два-три предложения — итог не нужен, "
    "не пересказывай сам себя.\n"
    "- Итог не вводит новых фактов и не добавляет того, чего нет выше."
)

def mandatory_output_rules() -> str:
    """Правила оформления, которые нельзя отменить пользовательским промптом.

    Задача «не показывать пользователю чанки» — продуктовая, а не пер-юзерная
    настройка, поэтому она не должна теряться, когда пользователь вписал свой
    системный промпт в настройках RAG.
    """
    parts = [CITATION_RULE if cite_sources_enabled() else NO_SERVICE_MARKUP_RULE]
    if answer_gaps_note_enabled():
        parts.append(GAPS_NOTE_RULE)
    if answer_summary_enabled():
        parts.append(SUMMARY_RULE)
    return "\n\n".join(parts)

def _active_rules() -> str:
    return STRICT_CONTEXT_RULES_LEGACY if _strict_answer_mode() == "strict" else SOFT_CONTEXT_RULES

def build_rag_user_instruction(with_citations: Optional[bool] = None) -> str:
    """Полный блок правил RAG: работа с контекстом + обязательное оформление.

    ```with_citations``` — явный override над ```RAG_CITE_SOURCES```:
    None (по умолчанию) — как задано в окружении; True/False — принудительно.
    """
    parts = [_active_rules()]
    if with_citations is None:
        parts.append(mandatory_output_rules())
    else:
        parts.append(CITATION_RULE if with_citations else NO_SERVICE_MARKUP_RULE)
        if answer_gaps_note_enabled():
            parts.append(GAPS_NOTE_RULE)
        if answer_summary_enabled():
            parts.append(SUMMARY_RULE)
    return "\n\n".join(parts)

def merge_strict_rag_system_prompt(existing: Optional[str], rag_override: Optional[str] = None) -> str:
    """Добавляет правила CONTEXT к системному промпту при RAG.

    Название сохранено для обратной совместимости; фактически добавляются мягкие
    правила (по умолчанию) либо строгие при RAG_STRICT_ANSWER_MODE=strict.

    Пользовательский ```rag_override``` заменяет правила работы с контекстом, но НЕ
    отменяет обязательное оформление: без служебной разметки и с итогом в конце.
    """
    custom = (rag_override or "").strip()
    if custom:
        block = f"{custom}\n\n{mandatory_output_rules()}"
    else:
        block = build_rag_user_instruction()
    if not existing or not str(existing).strip():
        return block
    ex = str(existing).strip()
    if block in ex:
        return ex
    if (not custom) and ("только предоставленный контекст (CONTEXT)" in ex or "Правила ответа по CONTEXT" in ex):
        return ex
    return f"{ex}\n\n{block}"